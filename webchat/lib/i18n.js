/** Look up a key; strings get {var} placeholders filled. Falls back to Indonesian. */
export function translate(lang, key, vars) {
  const value = DICT[normalizeLang(lang)][key] ?? DICT[DEFAULT_LANG][key];
  if (value === undefined) return key;
  if (typeof value !== 'string' || !vars) return value;
  return value.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
}

/** BCP 47 tag for dates, times and speech recognition. */
export function localeTag(lang) {
  return normalizeLang(lang) === 'en' ? 'en-GB' : 'id-ID';
}

/** Client-side: write the shared rs_lang cookie (1 year, readable by both sites). */
export function writeLangCookie(lang, { domain, secure } = {}) {
  if (typeof document === 'undefined') return;
  const parts = [
    `${LANG_COOKIE}=${normalizeLang(lang)}`,
    'Path=/',
    `Max-Age=${365 * 24 * 60 * 60}`,
    'SameSite=Lax',
  ];
  if (domain) parts.push(`Domain=${domain}`);
  if (secure) parts.push('Secure');
  document.cookie = parts.join('; ');
}
