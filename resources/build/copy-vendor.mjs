// Copies the browser assets the Laravel views need from node_modules into public/,
// so the site makes no requests to third-party CDNs (Brave Shields and ad blockers
// block cdn.tailwindcss.com, jsDelivr, unpkg and Google Fonts).
//
//   npm run build:vendor   (after changing a version in package.json)
//
// Writes: public/vendor/alpine, public/vendor/leaflet, public/vendor/maplibre, public/fonts and
// resources/css/fonts.css (the @font-face rules that site.css imports).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');
const nm = (...p) => path.join(root, 'node_modules', ...p);
const pub = (...p) => path.join(root, 'public', ...p);
const pkg = (name) => JSON.parse(fs.readFileSync(nm(name, 'package.json'), 'utf8'));
const copy = (from, to) => {
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(from, to);
};

