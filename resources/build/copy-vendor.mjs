// Leaflet (BSD-2-Clause): js, css and the marker/layer images the css points to.
for (const f of ['leaflet.js', 'leaflet.css']) copy(nm('leaflet', 'dist', f), pub('vendor', 'leaflet', f));
for (const f of fs.readdirSync(nm('leaflet', 'dist', 'images'))) copy(nm('leaflet', 'dist', 'images', f), pub('vendor', 'leaflet', 'images', f));
copy(nm('leaflet', 'LICENSE'), pub('vendor', 'leaflet', 'LICENSE'));

// MapLibre GL JS (BSD-3-Clause) for the 3D terrain view on the trail page. Loaded only
// when the hiker opens that view, never on page load. No source map (5 MB, not needed).
for (const f of ['maplibre-gl.js', 'maplibre-gl.css', 'LICENSE.txt']) copy(nm('maplibre-gl', 'dist', f), pub('vendor', 'maplibre', f));

// Fonts (SIL OFL 1.1) from Fontsource, latin + latin-ext only, woff2 only.
const fonts = [
    ['inter', 'Inter', [400, 500, 600, 700, 800]],
    ['barlow-condensed', 'Barlow Condensed', [700, 800]],
];
const subsets = ['latin-ext', 'latin'];
let css = `/* Generated by resources/build/copy-vendor.mjs from Fontsource. Do not edit. */\n`;
for (const [id, family, weights] of fonts) {
    const version = pkg(`@fontsource/${id}`).version;
    css += `\n/* ${family}: @fontsource/${id} ${version}, SIL Open Font License 1.1 (public/fonts/${id}/LICENSE) */\n`;
    copy(nm('@fontsource', id, 'LICENSE'), pub('fonts', id, 'LICENSE'));
    for (const weight of weights) {
        const source = fs.readFileSync(nm('@fontsource', id, `${weight}.css`), 'utf8');
        for (const subset of subsets) {
            const file = `${id}-${subset}-${weight}-normal.woff2`;
            const block = source.match(new RegExp(`/\\* ${id}-${subset}-${weight}-normal \\*/\\s*@font-face\\s*\\{[^}]*\\}`));
            const range = block && block[0].match(/unicode-range:\s*([^;]+);/);
            if (!range) throw new Error(`No ${subset} ${weight} face in @fontsource/${id}`);
            copy(nm('@fontsource', id, 'files', file), pub('fonts', id, file));
            css += `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${weight};src:url(/fonts/${id}/${file}) format('woff2');unicode-range:${range[1].trim()}}\n`;
        }
    }
}
fs.writeFileSync(path.join(root, 'resources', 'css', 'fonts.css'), css);
console.log(`alpine ${alpine.version}, leaflet ${pkg('leaflet').version}, maplibre-gl ${pkg('maplibre-gl').version}, fonts written`);
